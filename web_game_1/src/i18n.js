export class I18n {
  constructor() {
    let saved = null;
    try {
      saved = localStorage.getItem("memaybeo-language");
    } catch (error) {
      console.warn("Could not load language preference.", error);
    }
    this.language = saved === "vi" || saved === "en" ? saved : "en";
  }

  t(key, values = {}) {
    let text = translations[this.language][key] ?? translations.en[key] ?? key;
    for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  }

  apply() {
    document.documentElement.lang = this.language;
    document.title = this.language === "vi" ? "memaybeo — Miền Hoang Dã" : "memaybeo — The Wilds";
    document.querySelectorAll("[data-i18n]").forEach(element => {
      element.textContent = this.t(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(element => {
      element.setAttribute("aria-label", this.t(element.dataset.i18nAria));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(element => {
      element.innerHTML = this.t(element.dataset.i18nHtml);
    });
    document.getElementById("language-toggle").textContent = this.language === "en" ? "VI" : "EN";
    document.getElementById("language-toggle").setAttribute(
      "aria-label",
      this.language === "en" ? "Chuyển sang tiếng Việt" : "Switch to English",
    );
    const audioToggle = document.getElementById("audio-toggle");
    if (audioToggle) {
      const audioKey = audioToggle.getAttribute("aria-pressed") === "true" ? "muteAudio" : "enableAudio";
      audioToggle.setAttribute("aria-label", this.t(audioKey));
      audioToggle.title = this.t(audioKey);
    }
  }

  toggle() {
    this.language = this.language === "en" ? "vi" : "en";
    try {
      localStorage.setItem("memaybeo-language", this.language);
    } catch (error) {
      console.warn("Could not save language preference.", error);
    }
    this.apply();
  }
}
